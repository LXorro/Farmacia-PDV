CREATE PROCEDURE `OBTEDOCUENTA`(IN `PAR_CLIENTE_ID` INT)
BEGIN
  SELECT CAST(`DTFECHA` AS DATE) AS `FECHA`, -`DMONTO` AS `MONTO`, CONCAT('a-', `ID`) AS `TIPO`
    FROM `ABONOS` WHERE `CLIENTE_ID` = `PAR_CLIENTE_ID`
